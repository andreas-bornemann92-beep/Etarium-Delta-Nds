const { chromium }=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const url='http://127.0.0.1:8787/p/';
 const visit=async()=>{await page.goto(url,{waitUntil:'load'});await page.waitForFunction(()=>window.etariumDiagnostics,{timeout:12000})};
 const state=()=>page.evaluate(()=>window.etariumDiagnostics.getState());
 const step=async(dir,n)=>{for(let i=0;i<n;i++){const ok=await page.evaluate(d=>window.etariumDiagnostics.move(d),dir);if(!ok)throw Error('Blocked movement '+dir+' step '+i);await page.waitForTimeout(245)}};
 await visit();
 if((await state()).stage!=='title')throw Error('Title state failed');
 await page.locator('#j-new').click();
 if((await state()).stage!=='editor')throw Error('Editor state failed');
 await page.locator('#j-name').fill('KortexTester');
 await page.locator('#j-gender').selectOption('female');
 await page.locator('#j-confirm').click();
 await page.waitForFunction(()=>window.etariumDiagnostics.getState().stage==='world',{timeout:10000});
 const started=await state();
 if(!started.running||started.x!==24||started.y!==32)throw Error('Editor→world failed: '+JSON.stringify(started));
 await page.waitForFunction(()=>window.etariumDiagnostics.getState().renderFrames>20,{timeout:10000});
 await page.waitForFunction(()=>window.etariumDiagnostics.getState().animationFrames===18,{timeout:15000});
 if((await state()).bootErrors.length||errors.length)throw Error('Startup JS error '+JSON.stringify({errors,state:await state()}));
 if((await state()).npcs.length!==3)throw Error('NPC init failed');
 await page.waitForTimeout(1900);
 const toren=await state();
 if(!toren.npcs[1].moving&&toren.npcs[1].x===30&&toren.npcs[1].y===18)throw Error('NPC routine did not start');
 await step('up',5);await step('right',1);
 await page.locator('#action-a').click();
 if((await page.locator('#panel-title').innerText())!=='Mara')throw Error('Mara dialogue missing');
 await page.locator('#action-b').click();
 await step('up',2);await step('right',2);
 await page.locator('#action-a').click();
 if((await page.locator('#panel-title').innerText())!=='Elis')throw Error('Elis query missing');
 await page.locator('#action-a').click();
 if(!(await state()).npcResult.checked)throw Error('Query result missing');
 await page.locator('#action-b').click();
 await page.locator('#select').click();
 if((await state()).panel!=='select')throw Error('Select failed');
 await page.locator('#action-b').click();
 await page.locator('#start').click();
 if((await state()).panel!=='start')throw Error('Start menu failed');
 await page.getByRole('button',{name:'Speichern'}).click();
 await page.locator('#action-b').click();
 await page.locator('#start').click();
 await page.getByRole('button',{name:'Zum Titelbildschirm'}).click();
 await page.locator('#j-continue').click();
 if((await state()).stage!=='world')throw Error('Continue after save failed');
 if(errors.length||(await state()).bootErrors.length)throw Error('Runtime failures '+JSON.stringify(errors));
 await page.screenshot({path:'etarium-p-browser-proof.png',fullPage:true});
 console.log('PASS: Editor → World → NPC → Query → Start/Select → Save/Continue');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
