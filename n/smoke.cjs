const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8787/n/',{waitUntil:'load'});
 await page.waitForFunction(()=>window.etariumDiagnostics&&document.getElementById('j-new'));
 await page.locator('#j-new').click();
 await page.locator('#j-confirm').click();
 let initial=await page.evaluate(()=>window.etariumDiagnostics.getState());
 if(initial.stage!=='world'||initial.x!==24||initial.y!==32)throw Error('Spawn missing');
 await page.getByRole('button',{name:'Select',exact:true}).click();
 if((await page.locator('#panel-title').innerText())!=='Charakter')throw Error('Character select missing');
 await page.getByRole('button',{name:'Geister',exact:true}).click();
 if((await page.locator('#panel-title').innerText())!=='Geister')throw Error('Spirit select missing');
 if(!(await page.locator('#panel-body').innerText()).includes('0 / 10'))throw Error('Team size wrong');
 await page.getByRole('button',{name:'B',exact:true}).click();
 if((await page.evaluate(()=>window.etariumDiagnostics.getState())).panel!==null)throw Error('B back missing');
 await page.getByRole('button',{name:'Start',exact:true}).click();
 if((await page.locator('#panel-title').innerText())!=='Spielmenü')throw Error('Start menu missing');
 await page.getByRole('button',{name:'A',exact:true}).click();
 if((await page.evaluate(()=>window.etariumDiagnostics.getState())).panel!==null)throw Error('A confirm missing');
 const b=page.getByRole('button',{name:'B',exact:true});
 await b.dispatchEvent('pointerdown',{pointerId:1,pointerType:'touch',isPrimary:true});
 if(!(await page.evaluate(()=>window.etariumDiagnostics.getState())).sprinting)throw Error('B hold not running');
 await page.evaluate(()=>window.etariumDiagnostics.move('up'));
 let state=await page.evaluate(()=>window.etariumDiagnostics.getState());
 if(state.moveDuration>=150)throw Error('Run not faster');
 await b.dispatchEvent('pointerup',{pointerId:1,pointerType:'touch',isPrimary:true});
 if((await page.evaluate(()=>window.etariumDiagnostics.getState())).sprinting)throw Error('Run did not stop');
 await page.waitForTimeout(200);
 await page.getByRole('button',{name:'A',exact:true}).click();
 if((await page.evaluate(()=>window.etariumDiagnostics.getState())).panel!=='dialog')throw Error('A interact missing');
 await page.getByRole('button',{name:'B',exact:true}).click();
 if((await page.evaluate(()=>window.etariumDiagnostics.getState())).panel!==null)throw Error('B dialog back failed');
 if(errors.length)throw Error('Browser errors: '+errors.join(' | '));
 await page.screenshot({path:'etarium-n-controls.png',fullPage:true});
 console.log(JSON.stringify({PASS:true,initial,state},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
